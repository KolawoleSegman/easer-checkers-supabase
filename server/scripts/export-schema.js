// Writes supabase/schema.sql (same SQL the server runs on boot) so you can also
// paste it into the Supabase SQL editor.   Usage: npm run build && npm run db:schema
const fs = require('fs');
const path = require('path');
const { DDL } = require('../dist/src/db/ddl.js');
const out = path.join(__dirname, '..', 'supabase', 'schema.sql');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, '-- Generated by `npm run db:schema` from src/db/ddl.ts\n' + DDL);
console.log('wrote', out);
